// ===== حساب صاحب النظام (المطوّر): أعلى صلاحية =====
//
// حساب واحد يجمع الدورين: رتبته في القاعدة «admin» (فيقدر يدير الحسابات والإعدادات)
// لكنه بيشتغل سيلز عادي — يظهر مع الفريق في قوائم السيلز ولوحة عمله.
//
// **حساب صاحب النظام = أعلى صلاحية في النظام** (بطلب صريح من مالك الموقع):
//   ١) نطاق بياناته: كل بيانات الشركة — عملاء وأرقام وفيدباك ومكالمات وتذكيرات.
//   ٢) صلاحياته الإدارية: كاملة دائماً (إدارة الحسابات والإعدادات والحذف والتعديل).
//   ٣) الدخول إلى أي حساب (انتحال) بلا كلمة مرور — ومنهم حساب الـ CEO.
//
// ويظل سلوكه في **غرفة المدراء** سلوك سيلز (لا تصلك إشعارات الإدارة ورسائلها)،
// وفي **التوزيع التلقائي** هدف عادي مثل أي مندوب.
//
// ملاحظة مهمة: الحكم على «صاحب النظام» لا يعتمد على الرتبة المخزَّنة في السجل
// (role/dataScope)، لأن أي جهاز قديم بنسخة `crm_users` أقدم يقدر يكتب رتبة
// مخزَّنة مختلفة. فلو غُيّر `role` أو `dataScope` في أي نسخة، يبقى الحساب
// صاحب النظام بأعلى صلاحية — الحكم هنا في الكود مش في البيانات.
//
// الملف نقي (بلا شبكة) ويستعمله المتصفح والسيرفر بنفس الكود، فيبقى الحكم واحداً
// في المكانين.

const DEV_USERNAMES = ['mohamed'];

// حساب المطوّر: العلامة developer في السجل، أو اسم المستخدم المحفوظ (للبيانات القديمة)
export const isDeveloperAccount = (user) => {
  if (!user) return false;
  if (user.developer === true) return true;
  const name = String(user.username || '').trim().toLowerCase();
  return !!name && DEV_USERNAMES.includes(name);
};

// حساب صاحب النظام (المطوّر): أعلى صلاحية — مالك الموقع ومطوّره.
// العلامة developer في السجل، أو اسم المستخدم المحفوظ (للبيانات القديمة)،
// أو العلامة owner صراحةً. الحكم هنا بالاسم كمان، فيفقد الحساب صلاحيته
// لا لو الجهاز قديم كتب رتبة مختلفة، ولا لو السجل ناقص.
export const isOwnerAccount = (user) =>
  isDeveloperAccount(user) || user?.owner === true;

// ===== إداري وسيلز في نفس الوقت =====
// إداري اختار صراحةً أنه يستقبل أرقاماً (receivesLeads، مثل حساب فريدة).
// سلوكه في القوائم والفيدباك والحضور والنطاق سلوك سيلز (يظهر بلقبه الحقيقي CEO)،
// لكن صلاحياته الإدارية وقوائمه تبقى كما هي لأنه role = admin.
// ميزة عن `developer`: لا يُكتب له لقب «مطوّر» في أي مكان — واللقب يتبع رتبته.
export const worksAsSales = (user) =>
  isDeveloperAccount(user) ||
  (String(user?.role || '') === 'admin' && user?.receivesLeads === true);

// الرتبة التي يتصرف بها الحساب فعلياً (وليس رتبته المخزَّنة)
export const effectiveRoleOf = (user) => (worksAsSales(user) ? 'sales' : String(user?.role || 'sales'));

// مدير حقيقي في غرفة المدراء وفي إشعارات الإدارة
export const isManagerAccount = (user) => {
  const role = effectiveRoleOf(user);
  return role === 'admin' || role === 'supervisor';
};

// حساب إداري بصلاحيات (يدير الحسابات والإعدادات) — المطوّر منهم.
// صاحب النظام أعلى صلاحية: لا تُنقصه رتبة مخزَّنة في أي نسخة قديمة.
export const isAdminAccount = (user) =>
  isOwnerAccount(user) || String(user?.role || '') === 'admin';

// ===== نطاق بيانات الحساب — مصدر واحد للحقيقة =====
// null = يرى كل بيانات الشركة. غير ذلك = معرّفات الحسابات المسموح له بها.
// الترتيب: حساب صاحب النظام أولًا (أعلى صلاحية)، ثم إعداد صريح على الحساب
// (dataScope) ثم قاعدة الرتبة.
//   • حساب صاحب النظام (المطوّر): كل بيانات الشركة — أعلى صلاحية، بطلب من مالك الموقع.
//   • المدير التنفيذي (admin): كل بيانات الشركة — هو مَن يدير التوزيع.
//   • الإداري الذي يعمل سيلزاً (مثل فريدة) إن اختار «بياناته فقط»: بياناته هو.
//   • قائد الفريق: فريقه (لو عنده فريق فعلي — فريق فارغ ما يبقاش «كل الحسابات»).
//   • السيلز: نفسه فقط.
// «بياناته فقط» ما تُطبَّق على الإدارة إلا لو اختارها بنفسه من «تعديل الحساب».
export const dataScopeOf = (user, allUsers = []) => {
  if (!user || !user.id) return new Set();
  // صاحب النظام: كل بيانات الشركة — لا يقيّده أي إعداد ولا رتبة مخزَّنة.
  if (isOwnerAccount(user)) return null;
  if (user.dataScope === 'all') return null;
  const ownOnly = user.dataScope === 'own' || worksAsSales(user);
  if (!ownOnly && user.role === 'admin') return null;
  if (!ownOnly && user.role === 'supervisor' && String(user.team || '').trim()) {
    return new Set([
      user.id,
      ...(allUsers || [])
        .filter((u) => u && u.team === user.team)
        .map((u) => u.id),
    ]);
  }
  return new Set([user.id]);
};
